// Where recordings and HLS segments live. "local" = a directory shared with the
// LiveKit Egress container (self-hosting / development). "s3" = any
// S3-compatible bucket (AWS S3, Cloudflare R2, MinIO, Backblaze B2).
import { createReadStream, existsSync, statSync } from "node:fs";
import { rm } from "node:fs/promises";
import path from "node:path";
import { Readable } from "node:stream";
import { DeleteObjectsCommand, GetObjectCommand, ListObjectsV2Command, S3Client } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import { S3Upload } from "livekit-server-sdk";
import { notFound, unavailable } from "./errors";

export type StorageMode = "local" | "s3";

function env(name: string): string | undefined {
  const v = process.env[name];
  return v && v.trim() ? v.trim() : undefined;
}

export function storageMode(): StorageMode | null {
  if (env("S3_BUCKET") && env("S3_ACCESS_KEY") && env("S3_SECRET_KEY")) return "s3";
  if (env("RECORDINGS_DIR")) return "local";
  return null;
}

export function requireStorage(): StorageMode {
  const mode = storageMode();
  if (!mode) throw unavailable("Recording storage is not configured (set S3_* or RECORDINGS_DIR).", "storage_not_configured");
  return mode;
}

/** Path prefix as seen by the Egress service. */
export function egressPath(key: string): string {
  if (storageMode() === "s3") return key;
  const base = env("EGRESS_OUTPUT_DIR") ?? env("RECORDINGS_DIR")!;
  return path.posix.join(base, key);
}

export function egressS3Upload(): S3Upload | undefined {
  if (storageMode() !== "s3") return undefined;
  return new S3Upload({
    accessKey: env("S3_ACCESS_KEY")!,
    secret: env("S3_SECRET_KEY")!,
    bucket: env("S3_BUCKET")!,
    region: env("S3_REGION") ?? "auto",
    endpoint: env("S3_ENDPOINT") ?? "",
    forcePathStyle: env("S3_FORCE_PATH_STYLE") === "true",
  });
}

let client: S3Client | null = null;
function s3(): S3Client {
  return (client ??= new S3Client({
    region: env("S3_REGION") ?? "auto",
    endpoint: env("S3_ENDPOINT"),
    forcePathStyle: env("S3_FORCE_PATH_STYLE") === "true",
    credentials: { accessKeyId: env("S3_ACCESS_KEY")!, secretAccessKey: env("S3_SECRET_KEY")! },
  }));
}

/** Prevents path traversal: keys are generated by us and must stay inside the base dir. */
function localPath(key: string): string {
  const base = path.resolve(env("RECORDINGS_DIR")!);
  const full = path.resolve(base, key);
  if (!full.startsWith(base + path.sep)) throw notFound("File not found");
  return full;
}

export async function presignedUrl(key: string, seconds = 300, downloadName?: string): Promise<string> {
  return getSignedUrl(
    s3(),
    new GetObjectCommand({
      Bucket: env("S3_BUCKET")!,
      Key: key,
      ResponseContentDisposition: downloadName ? `attachment; filename="${downloadName.replace(/"/g, "")}"` : undefined,
    }),
    { expiresIn: seconds },
  );
}

export async function readText(mode: StorageMode, key: string): Promise<string> {
  if (mode === "local") {
    const p = localPath(key);
    if (!existsSync(p)) throw notFound("File not found");
    const { readFile } = await import("node:fs/promises");
    return readFile(p, "utf8");
  }
  const res = await s3().send(new GetObjectCommand({ Bucket: env("S3_BUCKET")!, Key: key }));
  return (await res.Body?.transformToString()) ?? "";
}

const TYPES: Record<string, string> = {
  ".mp4": "video/mp4",
  ".m3u8": "application/vnd.apple.mpegurl",
  ".ts": "video/mp2t",
  ".m4s": "video/iso.segment",
  ".ogg": "audio/ogg",
};

/** Streams a local file, honoring HTTP Range so video players can seek. */
export function localFileResponse(key: string, req: Request, opts: { download?: string; maxAge?: number } = {}): Response {
  const p = localPath(key);
  if (!existsSync(p)) throw notFound("File not found");
  const size = statSync(p).size;
  const type = TYPES[path.extname(p)] ?? "application/octet-stream";
  const headers: Record<string, string> = {
    "Content-Type": type,
    "Accept-Ranges": "bytes",
    "Cache-Control": opts.maxAge ? `private, max-age=${opts.maxAge}` : "private, no-store",
  };
  if (opts.download) headers["Content-Disposition"] = `attachment; filename="${opts.download.replace(/"/g, "")}"`;
  const range = req.headers.get("range")?.match(/^bytes=(\d*)-(\d*)$/);
  if (range && (range[1] || range[2])) {
    const start = range[1] ? Number(range[1]) : Math.max(size - Number(range[2]), 0);
    const end = range[1] && range[2] ? Math.min(Number(range[2]), size - 1) : size - 1;
    if (start >= size || start > end) return new Response(null, { status: 416, headers: { "Content-Range": `bytes */${size}` } });
    const stream = Readable.toWeb(createReadStream(p, { start, end })) as ReadableStream;
    return new Response(stream, {
      status: 206,
      headers: { ...headers, "Content-Length": String(end - start + 1), "Content-Range": `bytes ${start}-${end}/${size}` },
    });
  }
  const stream = Readable.toWeb(createReadStream(p)) as ReadableStream;
  return new Response(stream, { headers: { ...headers, "Content-Length": String(size) } });
}

/** Deletes a file or every object under a prefix. */
export async function deletePrefix(mode: StorageMode, prefix: string): Promise<void> {
  if (mode === "local") {
    await rm(localPath(prefix), { recursive: true, force: true });
    return;
  }
  let token: string | undefined;
  do {
    const list = await s3().send(new ListObjectsV2Command({ Bucket: env("S3_BUCKET")!, Prefix: prefix, ContinuationToken: token }));
    const keys = (list.Contents ?? []).map((o) => ({ Key: o.Key! }));
    if (keys.length) await s3().send(new DeleteObjectsCommand({ Bucket: env("S3_BUCKET")!, Delete: { Objects: keys } }));
    token = list.IsTruncated ? list.NextContinuationToken : undefined;
  } while (token);
}
